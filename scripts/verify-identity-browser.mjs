import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import express from 'express';
import cookieParser from 'cookie-parser';

const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
process.env.COIN_DATA_DIR = mkdtempSync(join(tmpdir(), 'coin-identity-'));
const { apiRouter } = await import('../server/dist/routes.js');
const { closeDb, getDb } = await import('../server/dist/db.js');
const app = express();
app.use(express.json(), cookieParser());
app.use('/api', apiRouter);
app.use(express.static(resolve('client/dist')));
const server = app.listen(0, '127.0.0.1');
await new Promise(r => server.once('listening', r));
const origin = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  for (const path of ['/', '/future/']) {
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin + path);
    const name = page.getByLabel('你的名字');
    await name.waitFor();
    const id = await page.getByTestId('player-random-id').innerText();
    assert.match(id, /^[0-9a-f-]{36}$/);
    assert.equal(await page.locator('.experience-grid').count(), 0);
    const confirm = page.getByRole('button', { name: '确认', exact: true });
    assert.equal(await confirm.isDisabled(), true);
    await name.fill('   ');
    assert.equal(await confirm.isDisabled(), true);
    for (const invalid of ['', '   ', '字'.repeat(41), 42]) {
      const response = await context.request.patch(origin + '/api/players/profile', { data: { display_name: invalid } });
      assert.equal(response.status(), 422);
    }
    await name.fill('  测试同学  ');
    await page.route('**/api/players/profile', route => route.fulfill({ status: 500, body: '{}' }), { times: 1 });
    await confirm.click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.locator('.experience-grid').count(), 0);
    await confirm.click();
    await page.locator('.experience-grid').waitFor();
    assert.equal(await page.locator('.identity-card b').innerText(), '测试同学');
    const saved = await (await context.request.post(origin + '/api/players/bootstrap')).json();
    assert.equal(saved.display_name, '测试同学');
    assert.notEqual(saved.player_uuid, id);
    const originalId = saved.player_uuid;
    const levels = await (await context.request.get(origin + '/api/levels' + (path === '/future/' ? '?competition=future' : ''))).json();
    const assignment = levels[0].keyboard_id;
    const attempt = await (await context.request.post(origin + '/api/attempts', { data: { assignment_key: assignment } })).json();
    await context.request.post(origin + `/api/attempts/${attempt.attempt_id}/stop`);
    await page.locator('[data-track-id="onboarding.mode.keyboard"]').click();
    await page.locator('.onboarding').waitFor({ state: 'detached' });
    await page.reload();
    await name.waitFor();
    assert.equal(await name.inputValue(), '');
    assert.equal(await page.getByTestId('player-random-id').innerText(), originalId);
    await name.fill(' 测试同学 ');
    await confirm.click();
    await page.locator('.experience-grid').waitFor();
    const same = await (await context.request.post(origin + '/api/players/bootstrap')).json();
    assert.equal(same.player_uuid, originalId);
    await page.reload();
    await name.waitFor();
    assert.equal(await page.locator('.experience-grid').count(), 0);
    await page.setViewportSize({ width: 375, height: 812 });
    const left = await name.boundingBox();
    const right = await page.getByTestId('player-random-id').boundingBox();
    assert.ok(left.x + left.width <= right.x && right.x + right.width <= 375);
    await name.fill('另一位同学');
    await name.press('Enter');
    await page.locator('.experience-grid').waitFor();
    const changed = await (await context.request.post(origin + '/api/players/bootstrap')).json();
    assert.notEqual(changed.player_uuid, originalId);
    assert.equal(changed.display_name, '另一位同学');
    assert.equal(await page.locator('.identity-card code').innerText(), changed.player_uuid);
    const progress = await (await context.request.get(origin + '/api/assignments/' + assignment)).json();
    assert.equal(progress.attempts.length, 0);
    assert.equal(progress.remaining_attempts, 3);
    assert.equal(getDb().prepare('SELECT display_name FROM players WHERE player_uuid = ?').get(originalId).display_name, '测试同学');
    assert.equal(getDb().prepare('SELECT player_uuid FROM attempts WHERE attempt_id = ?').get(attempt.attempt_id).player_uuid, originalId);
    const nextAttempt = await (await context.request.post(origin + '/api/attempts', { data: { assignment_key: assignment } })).json();
    assert.equal(getDb().prepare('SELECT player_uuid FROM attempts WHERE attempt_id = ?').get(nextAttempt.attempt_id).player_uuid, changed.player_uuid);
    await page.locator('[data-track-id="onboarding.mode.python_blank"]').click();
    await page.locator('.onboarding').waitFor({ state: 'detached' });
    assert.deepEqual(errors, []);
    await context.close();
    console.log(`${path}: identity validation, save/retry, refresh, mobile layout and both modes passed`);
  }
} finally {
  await browser?.close();
  await new Promise(r => server.close(r));
  closeDb();
}
